#!/usr/bin/env python3
"""Regenerate aws/src/drone_sdk_names.py: every public name the aircraft's code
sandbox offers to LLM-written code (daemon.execute_code), read from the drone
sources with ast, so the cloud can reject a call that does not exist before it
sends code to an aircraft.

    python3 aws/scripts/gen_drone_sdk_names.py

aws/src/test_code_check.py fails when the committed file is stale.
"""
from __future__ import annotations

import ast
from pathlib import Path

ECO = Path(__file__).resolve().parents[2]
SOURCES = [ECO / "drone/common/drone_sdk.py",
           *sorted((ECO / "drone/common/vehicles").glob("*.py"))]
OUT = ECO / "aws/src/drone_sdk_names.py"


def public_names(path: Path) -> set[str]:
    names = set()
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return {n for n in names if not n.startswith("_")}


def render() -> str:
    names = sorted(set().union(*(public_names(p) for p in SOURCES)))
    rel = ", ".join(str(p.relative_to(ECO)) for p in SOURCES[:1]) + ", drone/common/vehicles/*.py"
    body = "".join(f"    {n!r},\n" for n in names)
    return (f'"""GENERATED by aws/scripts/gen_drone_sdk_names.py from {rel}. Do not edit."""\n\n'
            f"SDK_NAMES = frozenset({{\n{body}}})\n")


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ECO)}")
