"""Wind: steady wind, von Karman turbulence, discrete gusts, local disturbance sources.

TurbulenceField -- a frozen, spatially coherent turbulence field built from random Fourier
    modes (Kraichnan's method) with the von Karman energy spectrum
        E(k) ~ (k/ke)^4 / (1 + (k/ke)^2)^(17/6),  ke = 0.747 / L
    Every vehicle samples the SAME field at its own position, so two aircraft a metre
    apart feel almost the same large gusts and differ only in the small ones: relative
    motion during a rendezvous is neither overstated (independent gusts) nor ignored
    (identical gusts). The field is advected with the mean wind (Taylor's hypothesis), so
    an aircraft flying through it sees the temporal spectrum Phi(omega) of the classic
    von Karman model at its airspeed; checks_phase1 measures that spectrum.

    A finite number of modes means a vehicle flying straight sees a line spectrum: the
    variance and the band-averaged spectrum are right, individual narrow frequency bins
    are not. 1000 modes per field put tens of lines in every third-octave band from
    0.02 Hz to 4 Hz at 20 m/s. Wavelengths below 1 m (smaller than the airframes, which
    average them out) are not generated.

    Horizontal and vertical components come from two independent fields with their own
    length scales and are scaled to exact per-component standard deviations, which is how
    the low-altitude MIL-HDBK-1797 model is anisotropic (sigma_u = sigma_v > sigma_w,
    L_u = 2 L_v > L_w). ``mil_hdbk_1797_low_altitude`` gives those numbers from altitude
    and the 20 ft wind speed (light 15 kt, moderate 30 kt, severe 45 kt).

DiscreteGust -- a 1-cosine gust pulse, spatially uniform.
WindField -- mean wind (optional power-law shear) + turbulence + gusts + local sources.
    A source is any callable (pos_m, t_s) -> wind_m_s added at that point; the docking
    work uses one for the airflow near the mothership.

Not modelled: turbulence generated by buildings, altitude variation of the turbulence
length scale within one run, gust gradients across a wingspan (each body samples one point).
"""
from __future__ import annotations

import math

import numpy as np

FT_PER_M = 1.0 / 0.3048
KT_TO_M_S = 0.514444


def mil_hdbk_1797_low_altitude(altitude_m: float, wind20_m_s: float) -> dict:
    """Low-altitude (< 1000 ft) von Karman parameters, MIL-HDBK-1797.

    sigma_w = 0.1 W20 ; sigma_u = sigma_v = sigma_w / (0.177 + 0.000823 h)^0.4
    L_u = 2 L_v = h / (0.177 + 0.000823 h)^1.2 ; 2 L_w = h   (h in ft inside the formula)
    Returned as the longitudinal scales of the two isotropic fields used here: horizontal
    field L = L_u, vertical field L = 2 L_w = h (transverse scale of an isotropic field is
    half its longitudinal scale).
    """
    h_ft = max(10.0, altitude_m * FT_PER_M)
    f = 0.177 + 0.000823 * h_ft
    sigma_w = 0.1 * wind20_m_s
    return {
        "sigma_u_m_s": sigma_w / f ** 0.4,
        "sigma_v_m_s": sigma_w / f ** 0.4,
        "sigma_w_m_s": sigma_w,
        "length_horizontal_m": (h_ft / f ** 1.2) / FT_PER_M,
        "length_vertical_m": altitude_m,
    }


def von_karman_longitudinal_psd(omega_rad_m: np.ndarray, sigma_m_s: float, L_m: float) -> np.ndarray:
    """One-sided spatial PSD of the longitudinal component, (m/s)^2 per (rad/m)."""
    return sigma_m_s ** 2 * (2 * L_m / math.pi) / (1 + (1.339 * L_m * omega_rad_m) ** 2) ** (5.0 / 6.0)


def von_karman_transverse_psd(omega_rad_m: np.ndarray, sigma_m_s: float, L_m: float) -> np.ndarray:
    """One-sided spatial PSD of a transverse component; L is the field's longitudinal scale."""
    x = (1.339 * L_m * omega_rad_m) ** 2
    return sigma_m_s ** 2 * (L_m / math.pi) * (1 + (8.0 / 3.0) * x) / (1 + x) ** (11.0 / 6.0)


class _RFMField:
    def __init__(self, L_m: float, n_modes: int, rng: np.random.Generator,
                 wavelength_min_m: float, wavelength_max_factor: float = 40.0):
        ke = 0.747 / L_m
        k_lo = 2 * math.pi / (wavelength_max_factor * L_m)
        k_hi = 2 * math.pi / wavelength_min_m
        edges = np.geomspace(k_lo, k_hi, n_modes + 1)
        # one mode per log-spaced bin, at a random (log-uniform) wavenumber inside it, so
        # the line spectrum a vehicle sees has no regular structure
        k = edges[:-1] * (edges[1:] / edges[:-1]) ** rng.uniform(0, 1, n_modes)
        dk = np.diff(edges)
        E = (k / ke) ** 4 / (1 + (k / ke) ** 2) ** (17.0 / 6.0)
        amp = np.sqrt(2 * E * dk)
        # random directions uniform on the sphere, polarisation perpendicular to k
        z = rng.uniform(-1, 1, n_modes)
        ph = rng.uniform(0, 2 * math.pi, n_modes)
        r = np.sqrt(1 - z * z)
        khat = np.stack([r * np.cos(ph), r * np.sin(ph), z], axis=1)
        tmp = rng.normal(size=(n_modes, 3))
        d = tmp - (tmp * khat).sum(1, keepdims=True) * khat
        d /= np.linalg.norm(d, axis=1, keepdims=True)
        self.K = khat * k[:, None]
        self.phase = rng.uniform(0, 2 * math.pi, n_modes)
        self.AD = amp[:, None] * d                      # (n, 3)
        self.var = 0.5 * (self.AD ** 2).sum(0)          # exact per-component variance (3,)

    def eval(self, x: np.ndarray) -> np.ndarray:
        # numpy 2.0 + Apple Accelerate raises spurious FP warnings on every matmul here
        # (values are finite); silence them locally and check finiteness ourselves.
        with np.errstate(all="ignore"):
            v = np.cos(self.K @ x + self.phase) @ self.AD
        if not np.isfinite(v).all():
            raise FloatingPointError("non-finite turbulence sample")
        return v


class TurbulenceField:
    def __init__(self, sigma_u_m_s: float, sigma_v_m_s: float, sigma_w_m_s: float,
                 length_horizontal_m: float, length_vertical_m: float, seed: int,
                 n_modes: int = 1000, wavelength_min_m: float = 1.0):
        rng = np.random.default_rng(seed)
        self.h = _RFMField(length_horizontal_m, n_modes, rng, wavelength_min_m)
        self.v = _RFMField(length_vertical_m, n_modes, rng, wavelength_min_m)
        # scale each component to its exact target sigma (u, v from the horizontal field
        # along world x/y; w from the vertical field)
        self.scale = np.array([
            sigma_u_m_s / math.sqrt(self.h.var[0]) if sigma_u_m_s > 0 else 0.0,
            sigma_v_m_s / math.sqrt(self.h.var[1]) if sigma_v_m_s > 0 else 0.0,
            sigma_w_m_s / math.sqrt(self.v.var[2]) if sigma_w_m_s > 0 else 0.0,
        ])
        self.sigmas_m_s = (sigma_u_m_s, sigma_v_m_s, sigma_w_m_s)

    def velocity(self, x_frozen_m: np.ndarray) -> np.ndarray:
        uh = self.h.eval(x_frozen_m)
        w = self.v.eval(x_frozen_m)[2]
        return np.array([uh[0], uh[1], w]) * self.scale


class DiscreteGust:
    """1-cosine pulse: v = A/2 (1 - cos(2 pi (t - t0) / T)) for t0 <= t <= t0 + T."""

    def __init__(self, start_s: float, duration_s: float, amplitude_m_s):
        self.t0, self.T = float(start_s), float(duration_s)
        self.A = np.asarray(amplitude_m_s, dtype=float)

    def velocity(self, t_s: float) -> np.ndarray:
        if t_s < self.t0 or t_s > self.t0 + self.T:
            return np.zeros(3)
        return 0.5 * self.A * (1 - math.cos(2 * math.pi * (t_s - self.t0) / self.T))


class WindField:
    def __init__(self, mean_m_s=(0.0, 0.0, 0.0), turbulence: TurbulenceField | None = None,
                 shear_exponent_nd: float = 0.0, shear_ref_height_m: float = 50.0):
        self.mean = np.asarray(mean_m_s, dtype=float)
        self.turbulence = turbulence
        self.gusts: list[DiscreteGust] = []
        self.sources: list = []
        self.shear_exp = shear_exponent_nd
        self.shear_ref = shear_ref_height_m

    def add_gust(self, g: DiscreteGust) -> None:
        self.gusts.append(g)

    def add_source(self, fn) -> None:
        self.sources.append(fn)

    def mean_at(self, pos_m: np.ndarray) -> np.ndarray:
        if self.shear_exp <= 0.0:
            return self.mean
        h = max(1.0, float(pos_m[2]))
        return self.mean * (h / self.shear_ref) ** self.shear_exp

    def ambient(self, pos_m: np.ndarray, t_s: float) -> np.ndarray:
        """Wind without local sources (what a vehicle's own wind estimator converges to)."""
        w = self.mean_at(pos_m).copy()
        if self.turbulence is not None:
            w += self.turbulence.velocity(pos_m - self.mean * t_s)
        for g in self.gusts:
            w += g.velocity(t_s)
        return w

    def velocity(self, pos_m: np.ndarray, t_s: float, exclude=None) -> np.ndarray:
        """Wind at a point. ``exclude`` = a source owner to skip (a body ignores its own wake)."""
        w = self.ambient(pos_m, t_s)
        for s in self.sources:
            if exclude is not None and getattr(s, "owner", None) is exclude:
                continue
            w = w + s(pos_m, t_s)
        return w
