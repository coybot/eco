"""Airflow next to the mothership -- an ADJUSTABLE, UNVALIDATED disturbance model.

This simulator cannot predict the flow around the mothership (no CFD, no wind tunnel, no
flight data). What is here is a physically shaped guess with one knob, ``gain`` (1.0 =
the nominal estimate below, 0 = off). Every result that depends on it says so; Phase 4
raises the gain until docking fails to find the margin.

Components (mothership body frame, added to the wind a quadcopter feels; the mothership
never feels its own):
  1. Horseshoe vortex of the wing. Bound vortex along the quarter-chord line, trailing
     vortices from the effective tips (b' = pi/4 b, elliptic loading) running aft 40 m,
     circulation Gamma = W / (rho V b'). Biot-Savart with a regularised core (radius
     ``core_m``). Gives the upwash ahead of the wing, the downwash behind it, and the
     slower air BELOW the wing (the bound vortex slows the flow under a lifting wing),
     i.e. what an under-fuselage dock sits in.
  2. Pusher slipstream. Actuator-disc momentum theory from the live pusher thrust: axial
     velocity increment growing from v_i at the disc to 2 v_i downstream, inside a
     contracting tube, smooth radial edge.
  3. Ceiling effect on the quad's rotors when they are close under a surface
     (Sanchez-Cuevas et al. 2017 fit, T/T_inf = 1 / (1 - (R/(d + 0.038))^2 / 6.92)), as a
     thrust multiplier; ``ceiling_gain`` scales the deviation from 1.

Not modelled at all: fuselage potential flow, wing-tip vortex roll-up dynamics, unsteady
wake shedding, the quad's own downwash hitting the mothership, rotor-rotor interaction,
and turbulence generated by the airframe.
"""
from __future__ import annotations

import math

import numpy as np


def _segment_induced(P, A, B, gamma, core):
    r1, r2 = P - A, P - B
    r0 = B - A
    c = np.cross(r1, r2)
    c2 = float(c @ c)
    n1, n2 = math.sqrt(float(r1 @ r1)), math.sqrt(float(r2 @ r2))
    if n1 < 1e-9 or n2 < 1e-9:
        return np.zeros(3)
    l0 = math.sqrt(float(r0 @ r0))
    k = float(r0 @ (r1 / n1 - r2 / n2))
    return gamma / (4 * math.pi) * c / (c2 + (core * l0) ** 2) * k


class MothershipFlow:
    def __init__(self, mothership, gain: float = 1.0, core_m: float = 0.10, ceiling_gain: float = 1.0):
        self.ms = mothership
        self.owner = mothership
        self.gain = gain
        self.core = core_m
        self.ceiling_gain = ceiling_gain
        g = mothership.cfg["geometry"]
        w = g["wing"]
        self.b = w["span_m"]
        self.bp = math.pi / 4 * self.b
        x_qc = w["center_x_m"] + w["chord_m"] / 4
        z = w["center_z_m"]
        self.A = np.array([x_qc, self.bp / 2, z])          # left tip (FLU: +y left)
        self.B = np.array([x_qc, -self.bp / 2, z])
        far = 40.0
        self.A_far = self.A + np.array([-far, 0.0, 0.0])
        self.B_far = self.B + np.array([-far, 0.0, 0.0])
        pu = g["pusher"]
        self.pc = np.array([pu["x_m"], 0.0, pu["z_m"]])
        self.pR = pu["diameter_m"] / 2
        self.sign = 1.0
        # orient the circulation: under the wing the induced flow must slow the relative
        # wind, i.e. point FORWARD (+x) in the body frame
        self.sign = 1.0 if self._horseshoe(np.array([x_qc, 0.0, z - 0.5]), 1.0)[0] > 0 else -1.0

    def _horseshoe(self, p, gamma):
        v = _segment_induced(p, self.A_far, self.A, gamma, self.core)
        v += _segment_induced(p, self.A, self.B, gamma, self.core)
        v += _segment_induced(p, self.B, self.B_far, gamma, self.core)
        return v

    def induced_body(self, p_body: np.ndarray) -> np.ndarray:
        ms = self.ms
        V = max(ms.stack.ap.airspeed_meas, 8.0)
        rho = ms.stack.phys.rho
        gamma = self.sign * ms.mass_kg() * 9.80665 / (rho * V * self.bp)
        v = self._horseshoe(p_body, gamma)
        # pusher slipstream (axial, toward -x)
        T = ms.stack.phys.last.get("thrust_n", 0.0)
        if T > 0:
            A = math.pi * self.pR ** 2
            vi = -V / 2 + math.sqrt(V * V / 4 + T / (2 * rho * A))
            dx = self.pc[0] - p_body[0]                     # > 0 behind the disc
            r = math.hypot(p_body[1] - self.pc[1], p_body[2] - self.pc[2])
            if dx > -self.pR:
                f_ax = 1.0 + dx / math.sqrt(self.pR ** 2 + dx * dx)            # 0 far ahead .. 2 far behind
                rt = self.pR * math.sqrt((1 + 0.0) / (1 + max(0.0, f_ax - 1)))  # contraction
                edge = 0.5 * (1 - math.tanh((r - rt) / (0.15 * self.pR)))
                v = v + np.array([-vi * f_ax * edge, 0.0, 0.0])
        return v

    def __call__(self, pos_w: np.ndarray, t_s: float) -> np.ndarray:
        if self.gain == 0.0:
            return np.zeros(3)
        b = self.ms.body
        p = b.R.T @ (pos_w - b.pos)
        if float(p @ p) > 30.0 ** 2:
            return np.zeros(3)
        return self.gain * (b.R @ self.induced_body(p))

    def ceiling_multiplier(self, rotor_gap_m: float, rotor_radius_m: float) -> float:
        if self.gain == 0.0 or self.ceiling_gain == 0.0 or rotor_gap_m > 1.0:
            return 1.0
        x = (rotor_radius_m / (max(rotor_gap_m, 0.01) + 0.038)) ** 2 / 6.92
        m = 1.0 / max(0.5, 1.0 - x)
        return 1.0 + self.gain * self.ceiling_gain * (m - 1.0)
